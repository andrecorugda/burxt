#!/usr/bin/env python3
"""Generate docs/packages.md — the list of Burxt packages that exist.

    python3 scripts/site-packages.py            # writes docs/packages.md
    python3 scripts/site-packages.py --check    # exits 1 if the file on disk is out of date

**This is the index, and deliberately not a registry.** The question it answers — "PHP has
Composer, JS has npm, where is ours?" — has a different answer here than in either, because those
two are different things from each other:

    npm       hosts the code. The registry IS the storage; publishing uploads a tarball.
    Composer  hosts nothing. Packagist maps a NAME to a git repo, and Composer clones from it.
    Go        has no registry at all. The import path IS the URL.

Burxt is Go's model, and `burxt fetch` plus `burxt.lock` is already the whole of Composer's
mechanism — a consumer just writes the URL out instead of looking it up. So the missing piece was
never a package manager; it was somewhere to LOOK. That is a list, and a list needs no server, no
namespace to police, no squatting policy and no uptime obligation.

**The list is authored, not scraped**, for the same reason `editors/vscode/pack.py`'s file list is:
a scrape would put whatever it found on a page a reader trusts. Adding a package is one entry here,
and every field in it has to be true — `the_reference_is_not_stale` regenerates this file and diffs
it, so the page cannot drift from this list.

**What no test here checks: that the tags still exist on the remotes.** That needs the network, and
the suite must pass offline — the same reason a build never fetches. So a tag deleted upstream will
be found by a reader, not by CI, and that is a deliberate hole rather than an oversight. It is
cheap to close by hand: `git ls-remote --tags <url>` per entry, and note that `ls-remote` sorts
lexically, so `burxt-0.12.1` comes BEFORE `burxt-0.9.1` and a `tail` reads the wrong end.

**A word on why there are no version ranges to show.** `spec/1.0/ROADMAP-1.0.md` C2: *"No version
ranges, ever: a dependency names one tag and the lockfile will pin one commit, so resolution is a
lookup rather than a solver."* That is what makes this page sufficient rather than a stopgap — an
index feeding a solver has to be complete and live, and an index feeding a human does not.
"""

import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "docs", "packages.md")

FRONT = '---\nlayout: default\ntitle: %s\nsection: packages\ndescription: "%s"\n---\n\n'

# Every Burxt package there is, and every field measured rather than remembered. `tag` is the
# newest tag published for Burxt consumption, which is not always the repository's newest tag —
# BMX versions its own format separately and publishes `burxt-*` tags for this.
#
# `manifest` records whether the repository declares its own `burxt.package`. A dependency
# resolves without one, because a package import is a path join under the fetched directory — but
# declaring one is what lets the package state its own name and version, so it is worth saying
# which have and which have not rather than implying all of them do.
#
# **`manifest` describes the TAG, not the tip**, and that distinction is not pedantic: BMX added a
# `burxt.package` the same afternoon this page was written, and flipping the flag would have been
# wrong, because `burxt-0.12.2` was already tagged without one. What a consumer fetches is the tag.
# So this flag may only change when a tag containing the manifest exists — verify with
# `git cat-file -e <tag>:burxt.package`, never by looking at somebody's working tree.
PACKAGES = [
    {
        "name": "bmx",
        "url": "https://github.com/andrecorugda/bmx",
        "tag": "burxt-0.12.2",
        "manifest": False,
        "what": "The BMX markup format — a parser and conformance suite, with the Burxt "
                "implementation under `burxt/`.",
    },
    {
        "name": "star-burxt",
        "url": "https://github.com/andrecorugda/star-burxt",
        "tag": "v0.2.0",
        "manifest": True,
        "what": "Components for Burxt: a `.sbmx` document is a component, and the generator "
                "turns one into Burxt source the compiler then judges.",
    },
]


def build():
    out = [FRONT % (
        "Packages",
        "Every Burxt package that exists, with the one line each needs to be used.",
    )]
    out.append("# Packages\n")
    out.append(
        "A Burxt package is **a git repository with a tag**. There is no registry to publish to "
        "and no account to create: the URL is the package's name, so nothing central has to agree "
        "that it exists. This page is the index — somewhere to look, which is the only part a list "
        "cannot replace.\n"
    )
    out.append(
        "To use one, name it in your `burxt.package` and fetch once. A build never touches the "
        "network, so the fetch is a separate step you run deliberately:\n"
    )
    out.append("```sh\nburxt fetch\n```\n")

    for p in PACKAGES:
        out.append("## %s\n" % p["name"])
        out.append("%s\n" % p["what"])
        out.append(
            "```\ndependency  %s  %s  %s\n```\n" % (p["name"], p["url"], p["tag"])
        )
        out.append(
            "Then `use \"%s/<file>.bx\";` from anywhere in your program. "
            "[The repository](%s).\n" % (p["name"], p["url"])
        )
        if not p["manifest"]:
            out.append(
                "> Declares no `burxt.package` of its own. It resolves anyway — a package import "
                "is a path join under the fetched directory — so this is a note rather than a "
                "warning.\n"
            )

    out.append("## What you get for free, without any of this\n")
    out.append(
        "The standard library is **not** a package. `lib/` ships beside the compiler and "
        "`use \"std/string.bx\";` reaches it with nothing declared and nothing fetched — which is "
        "why it resolves against exactly two roots, `BURXT_LIB` and the `lib/burxt` next to the "
        "running binary, and no others. A dependency you did not ask for is a dependency you "
        "cannot review.\n"
    )

    out.append("## Publishing one\n")
    out.append(
        "Tag a repository. That is the whole procedure — there is nothing to upload and nobody to "
        "ask. Two things make yours pleasant to depend on:\n"
    )
    out.append(
        "- **Declare a `burxt.package`** with a `name` and a `version`, so your package states its "
        "own identity rather than being known only by the URL somebody typed.\n"
        "- **Mark your interface `public`.** Everything is visible inside a package; only "
        "`public` declarations are reachable from a package that depends on yours, so what you do "
        "not mark stays yours to change. `burxt review --semver` then answers mechanically whether "
        "your next tag is a patch, a minor or a major.\n"
    )
    out.append(
        "To be found, add the **`burxt-lang`** topic to your repository. "
        "[github.com/topics/burxt-lang](https://github.com/topics/burxt-lang) is then an index "
        "GitHub maintains for you, and it costs one command:\n"
    )
    out.append("```sh\ngh repo edit --add-topic burxt-lang\n```\n")
    out.append(
        "To be listed here as well, open a pull request adding an entry to "
        "`scripts/site-packages.py`. The list is authored rather than scraped, because a page a "
        "reader trusts should not contain whatever a search happened to return.\n"
    )
    return "\n".join(out) + "\n"


def main():
    text = build()
    if "--check" in sys.argv:
        on_disk = open(OUT).read() if os.path.exists(OUT) else ""
        if on_disk != text:
            sys.exit("docs/packages.md is out of date — run: python3 scripts/site-packages.py")
        print("docs/packages.md is current")
        return
    with open(OUT, "w") as f:
        f.write(text)
    print("wrote docs/packages.md (%d packages)" % len(PACKAGES))


if __name__ == "__main__":
    main()
